function handleOptionClick() {
    const labels = document.querySelectorAll(".options label");
    labels.forEach(label => {
        label.addEventListener("click", () => {
            // Retirer la classe verte de tous les labels
            labels.forEach(l => l.style.backgroundColor = "orange");
            // Mettre le label cliqué en vert
            label.style.backgroundColor = "green";
        });
    });
}

function showQuestion() {
    const q = quiz[current];
    const questionDiv = document.querySelector(".question h3");
    const optionsDiv = document.querySelector(".options");

    questionDiv.innerHTML = `<img src="${q.image}" alt="img"> ${q.question}`;
    optionsDiv.innerHTML = "";

    if (q.type === "qcm") {
        q.options.forEach((opt,i) => {
            optionsDiv.innerHTML += `<label><input type="radio"  name="q${current}" value="${i}" > ${opt}</label>`;
        });
    } else {
        optionsDiv.innerHTML = `<input type="text" id="input-q${current}" placeholder="Votre réponse...">`;
    }

    document.getElementById("progress-bar").style.width = `${(current/quiz.length)*100}%`;
    
// Appeler après avoir affiché les options

handleOptionClick();

}

function nextQuestion() {
    const q = quiz[current];
    let userAnswer;

    if(q.type === "qcm"){
        const selected = document.querySelector(`input[name="q${current}"]:checked`);
        if(!selected) return alert("Choisis une réponse !");
        userAnswer = parseInt(selected.value);
        if(userAnswer === q.answer){ score++; correctSound.play(); }
        else { wrongSound.play(); }
    } else {
        const input = document.getElementById(`input-q${current}`);
        if(!input.value.trim()) return alert("Écris ta réponse !");
        userAnswer = input.value.trim().toLowerCase();
        if(userAnswer === q.answer.toLowerCase()){ score++; correctSound.play(); }
        else { wrongSound.play(); }
    }

    current++;
    if(current < quiz.length) showQuestion();
    else showResult();
}

